export const POSTGRES_SCHEMA_SQL = `-- KopiNusa Full-Stack Coffee Shop Relational Schema (PostgreSQL)

CREATE TABLE customers (
  id            VARCHAR(32) PRIMARY KEY,
  name          VARCHAR(120) NOT NULL,
  email         VARCHAR(160) UNIQUE NOT NULL,
  phone         VARCHAR(32),
  tier          VARCHAR(24) NOT NULL DEFAULT 'Regular',
  points        INTEGER NOT NULL DEFAULT 0,
  total_orders  INTEGER NOT NULL DEFAULT 0,
  total_spent   INTEGER NOT NULL DEFAULT 0,
  joined_at     DATE NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE inventory_items (
  id             VARCHAR(32) PRIMARY KEY,
  sku            VARCHAR(40) UNIQUE NOT NULL,
  name           VARCHAR(140) NOT NULL,
  category       VARCHAR(48) NOT NULL,
  stock          INTEGER NOT NULL DEFAULT 0,
  min_stock      INTEGER NOT NULL DEFAULT 0,
  unit           VARCHAR(12) NOT NULL,
  cost_per_unit  INTEGER NOT NULL DEFAULT 0,
  supplier       VARCHAR(120),
  last_restocked TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE menu_items (
  id            VARCHAR(32) PRIMARY KEY,
  sku           VARCHAR(40) UNIQUE NOT NULL,
  name          VARCHAR(140) NOT NULL,
  category      VARCHAR(48) NOT NULL,
  price         INTEGER NOT NULL,
  available     BOOLEAN NOT NULL DEFAULT TRUE,
  description   TEXT,
  prep_time_min INTEGER NOT NULL DEFAULT 3,
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE recipes (
  menu_item_id  VARCHAR(32) REFERENCES menu_items(id) ON DELETE CASCADE,
  inventory_id  VARCHAR(32) REFERENCES inventory_items(id) ON DELETE RESTRICT,
  quantity      INTEGER NOT NULL,
  PRIMARY KEY (menu_item_id, inventory_id)
);

CREATE TABLE orders (
  id             VARCHAR(32) PRIMARY KEY,
  order_number   VARCHAR(24) UNIQUE NOT NULL,
  customer_id    VARCHAR(32) REFERENCES customers(id) ON DELETE SET NULL,
  order_type     VARCHAR(20) NOT NULL,
  table_number   VARCHAR(24),
  payment_method VARCHAR(24) NOT NULL,
  status         VARCHAR(24) NOT NULL DEFAULT 'pending',
  total_amount   INTEGER NOT NULL,
  barista        VARCHAR(64) NOT NULL,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE order_items (
  id            VARCHAR(32) PRIMARY KEY,
  order_id      VARCHAR(32) REFERENCES orders(id) ON DELETE CASCADE,
  menu_item_id  VARCHAR(32) REFERENCES menu_items(id) ON DELETE RESTRICT,
  quantity      INTEGER NOT NULL,
  unit_price    INTEGER NOT NULL,
  subtotal      INTEGER NOT NULL,
  notes         TEXT
);`;
